// Usage: node scripts/make-manifest.mjs https://<user>.github.io/zee-ai
// Writes manifest.prod.xml pointing at the hosted URL (separate add-in Id from the dev manifest).
import { readFileSync, writeFileSync } from "node:fs";

const base = (process.argv[2] || "").replace(/\/+$/, "");
if (!/^https:\/\/[^\s]+$/.test(base)) {
  console.error("Usage: node scripts/make-manifest.mjs https://<user>.github.io/zee-ai");
  process.exit(1);
}
const PROD_ID = "7b1f3c2e-5a64-4c8e-9a1d-2f6e0c9b4d71";
let xml = readFileSync(new URL("../manifest.xml", import.meta.url), "utf8");
xml = xml
  .replaceAll("https://localhost:3100", base)
  .replace(/<Id>[^<]+<\/Id>/, `<Id>${PROD_ID}</Id>`)
  .replace(/<!--[\s\S]*?-->\s*/, "<!-- Zee AI – hosted manifest (generated by scripts/make-manifest.mjs). -->\n");
writeFileSync(new URL("../manifest.prod.xml", import.meta.url), xml);
console.log(`manifest.prod.xml written for ${base}`);
